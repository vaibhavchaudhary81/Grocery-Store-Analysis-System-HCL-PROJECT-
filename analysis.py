import numpy as np
import pandas as pd
from data_operations import load_data
def show_numpy_analysis():
    df = load_data()
    prices = df["Price"].to_numpy()
    one_d = np.array(prices)
    print("\n--- NUMPY 1D ARRAY ---")
    print(one_d)
    print("First price (index 0):", one_d[0])
    print("First five prices (slice):", one_d[:5])
    two_d = df[["Record_ID", "Price"]].to_numpy()
    print("\n--- NUMPY 2D ARRAY (first five rows) ---")
    print(two_d[:5, :])
    print("2D array price column:", two_d[:, 1])
    print("\n--- NUMPY STATISTICS ---")
    print("Sum:", np.sum(one_d))
    print("Mean:", round(np.mean(one_d), 2))
    print("Maximum:", np.max(one_d))
    print("Minimum:", np.min(one_d))
    print("Standard deviation:", round(np.std(one_d), 2))
def show_pandas_analysis():
    df = load_data()
    print("\n--- PANDAS DATAFRAME ---")
    print(df.head(10).to_string(index=False))
    print("\n--- SELECTED ROWS ---")
    print(df.iloc[0:5].to_string(index=False))
    print("\n--- SELECTED COLUMNS ---")
    print(df[["Product", "Store", "Price"]].head(10).to_string(index=False))
    print("\n--- FILTER: PRICE ABOVE 100 ---")
    print(df[df["Price"] > 100].to_string(index=False))
    print("\n--- SORTED BY PRICE (LOW TO HIGH) ---")
    print(df.sort_values("Price").head(10).to_string(index=False))
    print("\n--- GROUPBY: AVERAGE PRICE BY STORE ---")
    print(df.groupby("Store")["Price"].mean().round(2))
    print("\n--- MISSING VALUE CHECK ---")
    print(df.isnull().sum())
    df["Price"] = df["Price"].fillna(df["Price"].median())
    print("Missing values handled using median.")
    print("\n--- STATISTICAL SUMMARY ---")
    print(df["Price"].describe().round(2))
def compare_prices():
    df = load_data()
    table = df.pivot_table(index="Product", columns="Store",
                        values="Price", aggfunc="mean")
    print("\n--- GROCERY PRICE COMPARISON ---")
    print(table.round(2).to_string())
    print("\n--- CHEAPEST STORE FOR EACH PRODUCT ---")
    for product, row in table.iterrows():
        available = row.dropna()
        if not available.empty:
            cheapest_store = available.idxmin()
            cheapest_price = available.min()
            print(f"{product}: {cheapest_store} - Rs. {cheapest_price:.2f}")
    print("\n--- OVERALL AVERAGE PRICE BY STORE ---")
    print(df.groupby("Store")["Price"].mean().round(2).to_string())
